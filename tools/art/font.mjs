export const FONT_HEIGHT = 9;
export const LINE_HEIGHT = 10;

export function glyph(ch) {
  return G[ch] ?? G['?'];
}

export function textWidth(str) {
  return [...str].reduce((w, ch) => w + glyph(ch)[0].length + 1, 0) - 1;
}

/** Draws text with a 1px drop shadow (down-right), like classic JRPG windows. */
export function drawText(c, str, x, y, color = hex('#ffffff'), shadow = hex('#20203a')) {
  let cx = x;
  for (const ch of str) {
    const g = glyph(ch);
    for (const pass of shadow ? [shadow, color] : [color]) {
      const off = pass === shadow ? 1 : 0;
      g.forEach((row, j) => [...row].forEach((p, i) => p === '#' && c.set(cx + i + off, y + j + off, pass)));
    }
    cx += g[0].length + 1;
  }
  return cx;
}

/** Font sheet + metrics for the game: one cell per glyph, 8 wide x 10 tall. */
export function buildFontSheet() {
  const chars = Object.keys(G);
  const perRow = 16;
  const sheet = new Canvas(perRow * 8, Math.ceil(chars.length / perRow) * 10);
  const metrics = {};
  chars.forEach((ch, i) => {
    const x = (i % perRow) * 8, y = Math.floor(i / perRow) * 10;
    glyph(ch).forEach((row, j) => [...row].forEach((p, k) => p === '#' && sheet.set(x + k, y + j, hex('#ffffff'))));
    metrics[ch] = { x, y, w: glyph(ch)[0].length };
  });
  return { sheet, metrics };
}

/** BMFont XML for Phaser's bitmap font loader. */
export function buildFontXml({ sheet, metrics }, file = 'font.png') {
  const chars = Object.entries(metrics).map(
    ([ch, m]) => `    <char id="${ch.codePointAt(0)}" x="${m.x}" y="${m.y}" width="${m.w}" height="${FONT_HEIGHT}" xoffset="0" yoffset="0" xadvance="${m.w + 1}" page="0" />`,
  );
  return `<?xml version="1.0"?>
<font>
  <info face="spiritbound" size="${FONT_HEIGHT}" />
  <common lineHeight="${LINE_HEIGHT}" base="7" scaleW="${sheet.w}" scaleH="${sheet.h}" pages="1" />
  <pages><page id="0" file="${file}" /></pages>
  <chars count="${chars.length}">
${chars.join('\n')}
  </chars>
</font>
`;
}
