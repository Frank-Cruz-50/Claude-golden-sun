import Phaser from 'phaser';
import { GAME_HEIGHT, GAME_WIDTH, mapCacheKey, SceneKeys, tilesetTextureKey, UiKeys } from '../config';
import maps from '../data/maps.json';
import { SHADOW_TEXTURE } from '../entities/GridCharacter';
import { generateShadowTexture } from '../ui/placeholderSprites';
import { FONT_KEY } from '../ui/pixelText';
import fontPng from '../../assets/ui/font.png?url';
import fontXml from '../../assets/ui/font.xml?url';
import propsPng from '../../assets/ui/props.png?url';
import textboxPng from '../../assets/ui/textbox.png?url';
import window9Png from '../../assets/ui/window9.png?url';

const tilesetUrls = import.meta.glob('../../assets/tilesets/*.png', { query: '?url', import: 'default', eager: true }) as Record<
  string,
  string
>;
const spriteUrls = import.meta.glob('../../assets/sprites/*.png', { query: '?url', import: 'default', eager: true }) as Record<
  string,
  string
>;
const fileName = (path: string) => path.slice(path.lastIndexOf('/') + 1, path.lastIndexOf('.'));

const mapUrls = import.meta.glob('../../assets/maps/*.tmj', { query: '?url', import: 'default', eager: true }) as Record<
  string,
  string
>;

/** Loads maps, tilesets, character sheets, UI art, and the pixel font (all generated by tools/art). */
export class PreloadScene extends Phaser.Scene {
  constructor() {
    super(SceneKeys.Preload);
  }

  preload(): void {
    const barWidth = 120;
    const barX = (GAME_WIDTH - barWidth) / 2;
    const barY = GAME_HEIGHT / 2 + 4;
    this.add.rectangle(barX, barY, barWidth, 6).setOrigin(0).setStrokeStyle(1, 0xffffff);
    const fill = this.add.rectangle(barX + 1, barY + 1, 0, 4, 0xffffff).setOrigin(0);
    this.load.on('progress', (p: number) => (fill.width = (barWidth - 2) * p));

    this.load.bitmapFont(FONT_KEY, fontPng, fontXml);
    this.load.spritesheet(UiKeys.Props, propsPng, { frameWidth: 16, frameHeight: 16 });
    this.load.image(UiKeys.TextBox, textboxPng);
    this.load.image(UiKeys.Window9, window9Png);

    for (const [path, url] of Object.entries(tilesetUrls)) this.load.image(tilesetTextureKey(fileName(path)), url);
    // Character sheets: 24x32 frames, 3 per row (stand, stepA, stepB), rows down/left/right/up.
    for (const [path, url] of Object.entries(spriteUrls)) this.load.spritesheet(fileName(path), url, { frameWidth: 24, frameHeight: 32 });
    for (const [id, entry] of Object.entries(maps)) {
      const url = mapUrls[`../../assets/maps/${entry.file}`];
      if (!url) throw new Error(`maps.json: file not found for "${id}": ${entry.file}`);
      this.load.tilemapTiledJSON(mapCacheKey(id), url);
    }
  }

  create(): void {
    generateShadowTexture(this, SHADOW_TEXTURE);
    this.scene.start(SceneKeys.Title);
  }
}
